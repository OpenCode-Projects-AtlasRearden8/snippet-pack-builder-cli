"""Export a pack library to an espanso match file."""

from __future__ import annotations

from ..miniyaml import dumps
from ..models import Library

__all__ = ["export_espanso"]


def _select_snippets(library: Library, pack_name: str | None):
    for pack in library.packs.values():
        if pack_name and pack.name != pack_name:
            continue
        for snippet in pack.snippets:
            yield pack, snippet


def export_espanso(library: Library, pack_name: str | None = None) -> str:
    """Render the library as an espanso ``.yml`` match file.

    espanso this file under ``~/.config/espanso/match/`` (Linux/macOS) or
    ``%APPDATA%/espanso/match/`` (Windows).
    """
    matches = []
    for pack, snippet in _select_snippets(library, pack_name):
        label = snippet.title or snippet.notes
        matches.append(
            {
                "trigger": snippet.trigger,
                "replace": snippet.replace,
                **({"comment": label} if label else {}),
            }
        )
    payload = {
        "matches": matches,
    }
    body = dumps(payload)
    header = (
        "# espanso match file generated by snippetpack\n"
        "# Source: snippet YAML pack file(s), MIT licensed - Asdale Dynamics, LLC\n"
    )
    return header + body
