"""Export a pack library to an AutoHotkey v2 hotstring script."""

from __future__ import annotations

from ..models import Library, Snippet

__all__ = ["export_ahk"]


def _escape_hotstring(text: str) -> str:
    """Escape characters that AutoHotkey treats specially in hotstrings."""
    return text.replace("`", "``")


def _hotstring(snippet: Snippet) -> str:
    text = _escape_hotstring(snippet.replace)
    # espanso-style triggers often start with ':'; AHK cannot use that
    # reserved character, so the exporter drops leading colons.
    trigger = snippet.trigger.lstrip(":")
    if "\n" not in text:
        return f"::{trigger}::{text}"
    lines = text.split("\n")
    body = "\n".join(lines)
    return f"::{trigger}::\n(\n{body}\n)"


def export_ahk(library: Library, pack_name: str | None = None) -> str:
    """Render the library as an AutoHotkey v2 ``.ahk`` script."""
    out = [
        "; AutoHotkey v2 hotstrings generated by snippetpack",
        "; Source: snippet YAML pack file(s), MIT licensed - Asdale Dynamics, LLC",
        "; Place in your AHK v2 startup folder to use.",
        "",
        "#Requires AutoHotkey v2.0",
        "SendMode \"Input\"",
        "",
    ]
    last_pack = None
    for pack in library.packs.values():
        if pack_name and pack.name != pack_name:
            continue
        if last_pack not in (None, pack.name):
            out.append("")
        if pack.description or pack.name != last_pack:
            out.append(f"; --- pack: {pack.name} ---")
        for snippet in pack.snippets:
            if snippet.title:
                for line in snippet.title.splitlines():
                    out.append(f"; {line}")
            out.append(_hotstring(snippet))
            out.append("")
            last_pack = pack.name
    return "\n".join(out).rstrip("\n") + "\n"
